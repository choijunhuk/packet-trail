#!/usr/bin/env python3
"""Build standard Godot PO catalogs from reviewed, six-column production sources."""
import json
from pathlib import Path
from check_locales import LOCALES, ROOT, pseudo_expand


def build(root: Path = ROOT) -> None:
    directory = root / 'godot/locales'
    rows = {}
    for path in sorted(directory.glob('*.source.json')) + [directory / 'common.json']:
        source = json.loads(path.read_text(encoding='utf-8'))
        for key, values in source.items():
            if key in rows:
                raise ValueError(f'duplicate production key: {key}')
            if not isinstance(values, list) or len(values) != len(LOCALES) or any(not isinstance(v, str) or not v.strip() for v in values):
                raise ValueError(f'{key}: requires six nonempty translations')
            rows[key] = values
    for index, locale in enumerate(LOCALES):
        header = f'Project-Id-Version: Midnight Access 1.0\nLanguage: {locale}\nMIME-Version: 1.0\nContent-Type: text/plain; charset=UTF-8\nContent-Transfer-Encoding: 8bit\n'
        lines = ['# Generated by tools/build_locales.py; edit production JSON sources.', 'msgid ""', 'msgstr ' + json.dumps(header, ensure_ascii=False), '']
        for key, values in sorted(rows.items()):
            lines += ['msgid ' + json.dumps(key), 'msgstr ' + json.dumps(values[index], ensure_ascii=False), '']
        (directory / f'{locale}.po').write_text('\n'.join(lines), encoding='utf-8')
    fixture_keys = ['ROOM_SUBTITLE', 'ROOM_CONTROLS', 'NEW_GAME_CONFIRM', 'BACKGROUND_AUDIO', 'APPLY_SETTINGS', 'CREDITS_BODY', 'MISSION_PROGRESS']
    fixture = {'expansion_ratio': .4, 'viewports': [[1280, 720], [1600, 900]], 'font_scales': [1.0, 1.6], 'strings': {key: pseudo_expand(rows[key][1]) for key in fixture_keys}, 'acceptance': 'Render these samples with wrapping at both sizes and scales; data validation alone is not layout acceptance.'}
    (directory / 'pseudo-layout.json').write_text(json.dumps(fixture, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'ok': True, 'locales': len(LOCALES), 'messages_per_locale': len(rows)}))


if __name__ == '__main__':
    build()
